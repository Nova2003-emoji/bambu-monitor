// advance width (px) of a string in this font（与 drawQFontString 的 °C 连体一致）
static int16_t qfontWidth(const QFONT* f, const char* s) {
  int16_t w = 0;
  while (*s) {
    unsigned char c = (unsigned char)*s;
    if (c == 0xC2) { s++; continue; }              // UTF-8 前缀跳过
    if (c == 0xB0) {                                // °C 连体：° 圆 4px + C 宽
      w += 4; s++;
      if (*s == 'C' || *s == 'c') { w += f->width[*s - 0x20]; s++; }
      continue;
    }
    if (c >= 0x20 && c <= 0x7E) w += f->width[c - 0x20];
    else w += 1;
    s++;
  }
  return w;
}

// draw with display.drawPixel (GxEPD2/Adafruit frame buffer); bit=1 = ink.
// UTF-8 "°" (0xC2 0xB0) is drawn as a small ring (degree symbol, no glyph in font).
static void drawQFontString(int16_t x, int16_t y, const QFONT* f, const char* s, uint16_t ink) {
  while (*s) {
    unsigned char c = (unsigned char)*s;
    if (c == 0xC2) { s++; continue; }              // UTF-8 双字节前缀（跳过）
    if (c == 0xB0) {                                // °C 连体符号：° 圆（上标）+ C 整体渲染
      display.drawCircle(x + 2, y + 7, 1, ink);     // ° 圆
      display.drawPixel(x + 1, y + 6, ink);         // 四角补点
      display.drawPixel(x + 3, y + 6, ink);
      display.drawPixel(x + 1, y + 8, ink);
      display.drawPixel(x + 3, y + 8, ink);
      x += 4;
      s++;
      if (*s == 'C' || *s == 'c') {                 // 后跟 C → 组合 °C（C 在 ° 右下方）
        uint16_t iC = (*s - 0x20), wC = f->width[iC], offC = f->offset[iC];
        uint16_t wbC = (wC + 7) / 8;
        const uint8_t* pC = &f->table[offC];
        for (uint16_t r = 0; r < f->Height; r++)
          for (uint16_t c2 = 0; c2 < wC; c2++)
            if (pC[r * wbC + c2 / 8] & (0x80 >> (c2 % 8)))
              display.drawPixel(x + c2, y + r, ink);
        x += wC;
        s++;
      }
      continue;
    }
    if (c < 0x20 || c > 0x7E) { x += 1; s++; continue; }
    uint16_t idx = c - 0x20;
    uint16_t w = f->width[idx];
    uint16_t off = f->offset[idx];
    uint16_t wb = (w + 7) / 8;
    const uint8_t* ptr = &f->table[off];
    for (uint16_t row = 0; row < f->Height; row++) {
      for (uint16_t col = 0; col < w; col++) {
        if (ptr[row * wb + col / 8] & (0x80 >> (col % 8)))
          display.drawPixel(x + col, y + row, ink);
      }
    }
    x += w;
    s++;
  }
}
